"""Generate the catalogue pages of the docs from ../index.toml.

Writes (all git-ignored, regenerated at every docs build):

- ``packages/index.md``: every package (name, description, licence, modules, source);
- ``packages/modules.md``: every module and the packages whose library provides it (a module provided by several
  packages is flagged: those packages cannot be linked into one program);
- ``public/packages.json``: a shields.io endpoint badge with the number of packages.

Stdlib only (``tomllib``, Python 3.11+).
"""

from __future__ import annotations

import json
import sys
import tomllib
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlsplit

DOCS = Path(__file__).resolve().parents[1]
INDEX = DOCS.parent / "index.toml"
NOTE = "<!-- generated by docs/scripts/gen_catalog.py from index.toml: do not edit -->"


def _cell(text: str) -> str:
    """Markdown table cell: no pipes, no newlines, no stray HTML or Vue interpolation."""
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text.replace("<", "&lt;").replace(">", "&gt;").replace("{{", "{ {")


def _owner(source: str) -> str:
    parts = urlsplit(source)
    path = parts.path.strip("/").split("/")
    return path[0] if parts.netloc and path and path[0] else parts.netloc or "-"


def _anchor(name: str) -> str:
    return "pkg-" + "".join(c if c.isalnum() else "-" for c in name.lower())


def main() -> int:
    data = tomllib.loads(INDEX.read_text(encoding="utf-8"))
    packages = data.get("package", {})
    names = sorted(packages, key=str.lower)
    owners: dict[str, int] = defaultdict(int)
    providers: dict[str, list[str]] = defaultdict(list)
    for name in names:
        owners[_owner(packages[name]["source"])] += 1
        for module in packages[name].get("provides", []):
            providers[module].append(name)

    shared = {m: p for m, p in providers.items() if len(p) > 1}
    catalogue = [
        "---",
        "title: Packages",
        "pageClass: catalogue",
        "sidebar: false",
        "aside: false",
        "outline: false",
        "---",
        "",
        NOTE,
        "",
        "# Packages",
        "",
        f"The index lists **{len(names)} packages** from {len(owners)} owners, providing "
        f"**{len(providers)} modules**. Add one to your project with `fobis add NAME`, or install it for your "
        "compiler with `fobis pkg install NAME`.",
        "",
        "::: tip Versions",
        "The index holds no versions: `fobis info NAME` reads them from the package's source (its "
        "semantic-version tags), and `fobis add` pins the newest one.",
        ":::",
        "",
        "| Package | Description | Licence | Modules | Source |",
        "|---|---|---|---:|---|",
    ]
    for name in names:
        entry = packages[name]
        source = entry["source"]
        catalogue.append(
            f"| <span id=\"{_anchor(name)}\">**{_cell(name)}**</span> | {_cell(entry.get('description', ''))} "
            f"| {_cell(entry.get('license', '') or '-')} | {len(entry.get('provides', []))} "
            f"| [{_cell(_owner(source))}]({source}) |"
        )
    catalogue += ["", "## Owners", "", "| Owner | Packages |", "|---|---:|"]
    catalogue += [f"| {_cell(o)} | {n} |" for o, n in sorted(owners.items(), key=lambda kv: (-kv[1], kv[0].lower()))]

    modules = [
        "---",
        "title: Modules",
        "sidebar: false",
        "outline:",
        "  level: 2",
        "  label: By initial",
        "---",
        "",
        NOTE,
        "",
        "# Modules",
        "",
        f"Every module the indexed libraries provide ({len(providers)}), and the packages providing it: "
        "`fobis search --module NAME` gives the same answer, and `fobis add --module NAME` adds the package when only "
        "one provides it.",
        "",
        "::: warning Modules provided by several packages",
        f"{len(shared)} modules are defined by more than one package, usually because a package bundles another "
        "one's sources in its library. Such packages cannot be linked into one program: `fobis fetch` reports it.",
        ":::",
        "",
    ]
    initial = None
    for module in sorted(providers):
        letter = module[0].upper() if module[0].isalpha() else "#"
        if letter != initial:
            initial = letter
            modules += ["", f"## {letter}", "", "| Module | Provided by |", "|---|---|"]
        listed = ", ".join(f"[{_cell(p)}](./#{_anchor(p)})" for p in providers[module])
        flag = " ⚠️" if module in shared else ""
        modules.append(f"| `{_cell(module)}`{flag} | {listed} |")

    (DOCS / "packages").mkdir(exist_ok=True)
    (DOCS / "packages" / "index.md").write_text("\n".join(catalogue) + "\n", encoding="utf-8")
    (DOCS / "packages" / "modules.md").write_text("\n".join(modules) + "\n", encoding="utf-8")
    (DOCS / "public").mkdir(exist_ok=True)
    badge = {"schemaVersion": 1, "label": "packages", "message": str(len(names)), "color": "blue"}
    (DOCS / "public" / "packages.json").write_text(json.dumps(badge) + "\n", encoding="utf-8")
    print(f"catalogue: {len(names)} packages, {len(providers)} modules ({len(shared)} shared)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
